interface I18nContextType {
  lang: string;
  setLang: (lang: string) => void;
  t: (key: string, vars?: Record<string, string>) => string;
}

const I18nContext = createContext<I18nContextType>({ lang: 'en', setLang: () => {}, t: (k) => k });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState('en');

  useEffect(() => {
    const saved = localStorage.getItem('lf_lang') || 'en';
    setLangState(saved);
  }, []);

  const setLang = (l: string) => {
    setLangState(l);
    localStorage.setItem('lf_lang', l);
  };

  const tFunc = (key: string, vars?: Record<string, string>) => {
    let str = t[lang]?.[key] || t['en']?.[key] || key;
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        str = str.replace(`{${k}}`, v);
      });
    }
    return str;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t: tFunc }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  return useContext(I18nContext);
}
